/**
 * boot.ts — где взять адрес бота ДО того, как поднимется приложение.
 *
 * Адрес API приезжает параметром `?api=` от бота и запоминается. Но приложение
 * открывают и без ссылки: набрали адрес страницы руками, запустили ярлык,
 * добавленный до того, как параметр появился, переустановили — и обращаться
 * оказывается некуда. Человек при этом ничего плохого не сделал, а видел экран
 * «укажите адрес сервера», то есть вопрос, ответа на который у него нет.
 *
 * Поэтому адрес ПУБЛИКУЕТСЯ рядом с самим приложением — файлом `api.txt` на
 * том же GitHub Pages. Файл читается ровно один раз, при старте, и только
 * когда адреса нет ни в ссылке, ни в памяти: он нужен, чтобы приложение
 * поднялось само, а не чтобы спрашивать сеть на каждом запуске.
 *
 * Адрес тоннеля меняется при его рестарте — тогда меняется и файл, одной
 * строкой (`tools/set_api.sh`), и подхватывают его сразу все устройства.
 * Ссылка и память остаются главнее файла: их человек получил от бота лично.
 *
 * Модуль намеренно НЕ зависит от api.ts: тот читает адрес в момент импорта,
 * а значит должен импортироваться уже после нас.
 */

/** Ключ тот же, что в api.ts. Держать его в двух местах плохо, но иначе
 *  импорт api.ts случился бы до чтения адреса — то есть до того, как он есть. */
export const API_KEY = "prometey.api";

/** Сколько ждём файл. Это задержка первого экрана, поэтому она короткая:
 *  не дождались — приложение спросит адрес само, а не будет висеть. */
const WAIT_MS = 2500;

/** Прочитать опубликованный адрес. Пусто — файла нет, он пуст или сеть легла. */
export async function fetchPublishedApi(): Promise<string> {
  const url = new URL(`${import.meta.env.BASE_URL}api.txt`, location.href).toString();
  try {
    const r = await fetch(url, { cache: "no-store", signal: AbortSignal.timeout(WAIT_MS) });
    if (!r.ok) return "";
    const text = await r.text();
    /* Строки с решёткой — пояснение, и в нём стоит ПРИМЕР адреса. Не выкинув
       их, приложение уехало бы по выдуманному адресу из комментария: ровно
       это и случилось на первом же прогоне. Остаётся первое слово, похожее на
       адрес; http пропускаем только для локальной разработки — на странице по
       https браузер такой запрос всё равно заблокирует, и адрес молча не
       работал бы. */
    const found = text
      .split(/\r?\n/)
      .filter((line) => !line.trim().startsWith("#"))
      .join(" ")
      .split(/\s+/)
      .find((s) => /^https:\/\//.test(s) ||
                   /^http:\/\/(127\.0\.0\.1|localhost)(:|\/|$)/.test(s)) || "";
    return found.replace(/\/+$/, "");
  } catch {
    return "";
  }
}

function remembered(): string {
  try {
    return localStorage.getItem(API_KEY) || "";
  } catch {
    return "";
  }
}

/** Адрес известен из ссылки, памяти или сборки — файл не нужен. */
function known(): boolean {
  return Boolean(
    new URLSearchParams(location.search).get("api") ||
    remembered() ||
    import.meta.env.VITE_API_BASE,
  );
}

/** Вызывается ПЕРЕД загрузкой приложения. Не бросает никогда: без адреса
 *  приложение поднимется и попросит его у человека, а упавший старт не
 *  попросит ничего. */
export async function bootApi(): Promise<void> {
  if (known()) return;
  const url = await fetchPublishedApi();
  if (!url) return;
  try {
    localStorage.setItem(API_KEY, url);
  } catch {
    /* приватное окно — адрес просто не запомнится, экран входа спросит сам */
  }
}

/** Перечитать опубликованный адрес по просьбе человека («бот не отвечает»).
 *  Возвращает адрес, если он ИНОЙ, — тогда есть смысл перезагружаться. */
export async function refreshApi(): Promise<string> {
  const url = await fetchPublishedApi();
  if (!url) throw new Error("рядом с приложением нет опубликованного адреса");
  if (url === remembered()) throw new Error("опубликован тот же адрес — бот не отвечает по нему");
  localStorage.setItem(API_KEY, url);
  return url;
}
